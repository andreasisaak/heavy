const manifest101 = `# Generated by heavy at session start and after /reload-plugins; a heavy of a newer version writes it again.
id = "local.heavy-queue"
name = "Heavy Queue"
version = "1.0.1"
min_herdr_version = "0.9.1"
description = "Shows each heavy run of an agent in a sidebar row of its own (pane tokens heavy, heavy_2, heavy_3): running, paused, waiting or just ended, with its minutes"
platforms = ["macos", "linux"]

[[startup]]
command = ["/plugins/heavy 1.0.1/bin/heavy", "--herdr-refresh"]

[[actions]]
id = "refresh"
title = "Refresh the heavy queue in the sidebar"
command = ["/plugins/heavy 1.0.1/bin/heavy", "--herdr-refresh"]

[[actions]]
id = "forward"
title = "heavy: move the queued run of this pane one place ahead"
command = ["/plugins/heavy 1.0.1/bin/heavy", "--herdr-forward"]

[[actions]]
id = "dashboard"
title = "heavy: open the dashboard next to this pane"
command = ["/bin/sh", "-c", "exec \"${HERDR_BIN_PATH:-herdr}\" plugin pane open --plugin local.heavy-queue --entrypoint dashboard --placement split"]

[[events]]
on = "pane.agent_detected"
command = ["/plugins/heavy 1.0.1/bin/heavy", "--herdr-refresh"]

[[panes]]
id = "dashboard"
title = "heavy dashboard"
command = ["/plugins/heavy 1.0.1/bin/heavy", "--dashboard"]
`

func pluginOf(t *testing.T, version string) herdr.Plugin {
	t.Helper()
	return herdr.Plugin{Data: t.TempDir(), Version: version, Heavy: "/plugins/heavy " + version + "/bin/heavy"}
}

// manifestOf writes a manifest of version into the plugin's folder, as an installed heavy of that version would.
func manifestOf(t *testing.T, plugin herdr.Plugin, version string) string {
	t.Helper()
	return manifestAt(t, plugin, version, installed(t, version))
}

// manifestAt writes a manifest of version whose commands run heavy.
func manifestAt(t *testing.T, plugin herdr.Plugin, version, heavy string) string {
	t.Helper()
	other := herdr.Plugin{Data: plugin.Data, Version: version, Heavy: heavy}
	if err := other.Generate(); err != nil {
		t.Fatalf("writing the manifest of %s: %v", version, err)
	}
	return other.Manifest()
}

// installed is the path of a heavy binary of version that exists, as in the plugin cache.
func installed(t *testing.T, version string) string {
	t.Helper()
	heavy := filepath.Join(t.TempDir(), "heavy", version, "bin", "heavy")
	if err := os.MkdirAll(filepath.Dir(heavy), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(heavy, []byte("#!/bin/sh\n"), 0o755); err != nil {
		t.Fatal(err)
	}
	return heavy
}

func readManifest(t *testing.T, plugin herdr.Plugin) string {
	t.Helper()
	data, err := os.ReadFile(plugin.ManifestPath())
	if err != nil {
		t.Fatal(err)
	}
	return string(data)
}

// G12: the manifest lies in CLAUDE_PLUGIN_DATA and runs this version's heavy by its absolute path
func TestManifestRunsThisHeavyByItsAbsolutePath(t *testing.T) {
	plugin := pluginOf(t, "1.0.1")

	err := plugin.Generate()

	check(t, "error", errorText(err), "<nil>")
	check(t, "path", plugin.ManifestPath(), filepath.Join(plugin.Data, "herdr", "heavy-queue", "herdr-plugin.toml"))
	check(t, "manifest", readManifest(t, plugin), manifest101)
}

// G12: versions compare as numbers, and a heavy of an older or the same version leaves the manifest as it is
func TestManifestOfAnOlderVersionIsReplacedOnlyByANewerOne(t *testing.T) {
	cases := []struct {
		present, this string
		replaced      bool
	}{
		{"1.0.0", "1.0.1", true},
		{"1.0.1", "1.0.0", false},
		{"1.0.1", "1.0.1", false},
		{"0.9.0", "0.10.0", true},
		{"0.10.0", "0.9.0", false},
		{"1.0", "1.0.1", true},
		{"1.0.1", "1.0", false},
	}
	for _, current := range cases {
		t.Run(current.present+" then "+current.this, func(t *testing.T) {
			plugin := pluginOf(t, current.this)
			present := manifestOf(t, plugin, current.present)

			err := plugin.Generate()

			want := present
			if current.replaced {
				want = plugin.Manifest()
			}
			check(t, "error", errorText(err), "<nil>")
			check(t, "manifest", readManifest(t, plugin), want)
		})
	}
}

func TestManifestWithAVersionHeavyDidNotWriteFailsWithTheLine(t *testing.T) {
	for name, content := range map[string]string{
		`version = "1.0.x"`: "id = \"local.heavy-queue\"\nversion = \"1.0.x\"\n",
		"no version line":   "id = \"local.heavy-queue\"\n",
	} {
		t.Run(name, func(t *testing.T) {
			plugin := pluginOf(t, "1.0.1")
			if err := os.MkdirAll(filepath.Dir(plugin.ManifestPath()), 0o755); err != nil {
				t.Fatal(err)
			}
			if err := os.WriteFile(plugin.ManifestPath(), []byte(content), 0o644); err != nil {
				t.Fatal(err)
			}

			err := plugin.Generate()

			check(t, "error", errorText(err), "heavy: "+plugin.ManifestPath()+`: expected a line version = "<numbers separated by dots>", got `+name)
			check(t, "manifest", readManifest(t, plugin), content)
		})
	}
}

// a heavy outside a plugin, such as one built for a test, has no version to write
func TestManifestOfAHeavyWithoutVersionFails(t *testing.T) {
	plugin := pluginOf(t, "")

	err := plugin.Generate()

	check(t, "error", errorText(err), "heavy: the heavy binary /plugins/heavy /bin/heavy has no plugin version (.claude-plugin/plugin.json next to its bin/), so the herdr plugin is not generated")
}

func TestManifestOfAVersionThatIsNoDottedNumberFails(t *testing.T) {
	plugin := pluginOf(t, "1.0.0-beta")

	err := plugin.Generate()

	check(t, "error", errorText(err), "heavy: the plugin version 1.0.0-beta of /plugins/heavy 1.0.0-beta/bin/heavy is no numbers separated by dots, so the herdr plugin is not generated")
	_, statError := os.Stat(filepath.Join(plugin.Data, "herdr"))
	check(t, "folder made", os.IsNotExist(statError), true)
}

func TestManifestFailsWithThePathWhenItsFolderCannotBeCreated(t *testing.T) {
	plugin := pluginOf(t, "1.0.1")
	if err := os.Chmod(plugin.Data, 0o500); err != nil {
		t.Fatal(err)
	}
	t.Cleanup(func() { _ = os.Chmod(plugin.Data, 0o700) })

	err := plugin.Generate()

	check(t, "error", errorText(err), "heavy: generating the herdr plugin: mkdir "+filepath.Join(plugin.Data, "herdr")+": permission denied")
}

func TestManifestFailsWithThePathWhenItCannotBeRead(t *testing.T) {
	plugin := pluginOf(t, "1.0.1")
	if err := os.MkdirAll(plugin.ManifestPath(), 0o755); err != nil {
		t.Fatal(err)
	}

	err := plugin.Generate()

	check(t, "error", errorText(err), "heavy: reading the herdr plugin manifest: read "+plugin.ManifestPath()+": is a directory")
}

// a path with a quote, a backslash or a control character stays one TOML string
func TestManifestQuotesThePathAsATomlString(t *testing.T) {
	plugin := pluginOf(t, "1.0.1")
	plugin.Heavy = "/plugins/he\"avy\\\t/bin/heavy"

	err := plugin.Generate()

	check(t, "error", errorText(err), "<nil>")
	check(t, "manifest", readManifest(t, plugin), strings.ReplaceAll(manifest101, `"/plugins/heavy 1.0.1/bin/heavy"`, `"/plugins/he\"avy\\\u0009/bin/heavy"`))
}
