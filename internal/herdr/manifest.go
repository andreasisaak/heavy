package herdr

import (
	"errors"
	"fmt"
	"io/fs"
	"os"
	"path/filepath"
	"strings"
)

// manifestTemplate is herdr-plugin.toml: the version, then the commands of startup, the actions refresh, forward
// and dashboard, the event and the pane dashboard, each string a TOML basic string.
const manifestTemplate = `# Generated by heavy at session start and after /reload-plugins; a heavy of a newer version writes it again.
id = "local.heavy-queue"
name = "Heavy Queue"
version = %[1]s
min_herdr_version = "0.9.1"
description = "Shows each heavy run of an agent in a sidebar row of its own (pane tokens heavy, heavy_2, heavy_3): running, paused, waiting or just ended, with its minutes"
platforms = ["macos", "linux"]

[[startup]]
command = %[2]s

[[actions]]
id = "refresh"
title = "Refresh the heavy queue in the sidebar"
command = %[2]s

[[actions]]
id = "forward"
title = "heavy: move the queued run of this pane one place ahead"
command = %[3]s

[[actions]]
id = "dashboard"
title = "heavy: open the dashboard next to this pane"
command = %[4]s

[[events]]
on = "pane.agent_detected"
command = %[2]s

[[panes]]
id = "dashboard"
title = "heavy dashboard"
command = %[5]s
`

// openDashboard is the shell line of the action dashboard: herdr opens the pane dashboard as a split of the
// focused pane; HERDR_BIN_PATH is the herdr that runs the plugin.
const openDashboard = `exec "${HERDR_BIN_PATH:-herdr}" plugin pane open --plugin local.heavy-queue --entrypoint dashboard --placement split`

// Plugin is the herdr plugin of one installed heavy (design G12). /heavy:herdr links its folder once; every newer
// heavy rewrites the manifest in place, so the link never has to move.
type Plugin struct {
	// Data is CLAUDE_PLUGIN_DATA, "" when Claude Code did not set it.
	Data string
	// Version is the plugin version of Heavy, from .claude-plugin/plugin.json next to its bin/.
	Version string
	// Heavy is the absolute path of the heavy binary the plugin's commands run.
	Heavy string
}

// ManifestPath is ${CLAUDE_PLUGIN_DATA}/herdr/heavy-queue/herdr-plugin.toml.
func (p Plugin) ManifestPath() string {
	return filepath.Join(p.Data, "herdr", "heavy-queue", "herdr-plugin.toml")
}

// Manifest is the text of the manifest for this heavy.
func (p Plugin) Manifest() string {
	return fmt.Sprintf(manifestTemplate, quoted(p.Version), command(p.Heavy, "--herdr-refresh"), command(p.Heavy, "--herdr-forward"),
		command("/bin/sh", "-c", openDashboard), command(p.Heavy, "--dashboard"))
}

// Generate writes the manifest unless the one there is of the same or a newer version and its heavy is still
// installed, so a session of an older heavy never takes the sidebar back from a working newer one. Sessions of several versions may start at once: the check runs again under
// a lock before the write, and the new file replaces the old one in one rename. Reading the manifest is all it
// does when the manifest is current, which keeps it cheap enough for the guard.
func (p Plugin) Generate() error {
	if p.Version == "" {
		return fmt.Errorf("heavy: the heavy binary %s has no plugin version (.claude-plugin/plugin.json next to its bin/), so the herdr plugin is not generated", p.Heavy)
	}
	mine, valid := versionNumbers(p.Version)
	if !valid {
		return fmt.Errorf("heavy: the plugin version %s of %s is no numbers separated by dots, so the herdr plugin is not generated", p.Version, p.Heavy)
	}
	if stale, err := p.stale(mine); err != nil || !stale {
		return err
	}
	folder := filepath.Dir(p.ManifestPath())
	if err := os.MkdirAll(folder, 0o755); err != nil {
		return fmt.Errorf("heavy: generating the herdr plugin: %w", err)
	}
	unlock, err := lock(folder + ".lock")
	if err != nil {
		return err
	}
	defer unlock()
	if stale, err := p.stale(mine); err != nil || !stale {
		return err
	}
	written := p.ManifestPath() + ".new"
	if err := os.WriteFile(written, []byte(p.Manifest()), 0o644); err != nil {
		return fmt.Errorf("heavy: generating the herdr plugin: %w", err)
	}
	if err := os.Rename(written, p.ManifestPath()); err != nil {
		return fmt.Errorf("heavy: generating the herdr plugin: %w", err)
	}
	return nil
}

// stale reports whether the manifest is missing, names a version older than mine, or runs a heavy that is gone,
// whatever its version: a manifest of a removed version runs nothing. Only a current manifest costs the stat.
func (p Plugin) stale(mine []int) (bool, error) {
	data, err := os.ReadFile(p.ManifestPath())
	if errors.Is(err, fs.ErrNotExist) {
		return true, nil
	}
	if err != nil {
		return false, fmt.Errorf("heavy: reading the herdr plugin manifest: %w", err)
	}
	present, err := manifestVersion(p.ManifestPath(), data)
	if err != nil {
		return false, err
	}
	if older(present, mine) {
		return true, nil
	}
	heavy, err := manifestHeavy(p.ManifestPath(), data)
	if err != nil {
		return false, err
	}
	return gone(heavy)
}

// command is an argv as a TOML array.
func command(arguments ...string) string {
	words := make([]string, len(arguments))
	for index, argument := range arguments {
		words[index] = quoted(argument)
	}
	return "[" + strings.Join(words, ", ") + "]"
}

// quoted is text as a TOML basic string.
func quoted(text string) string {
	var builder strings.Builder
	builder.WriteByte('"')
	for _, character := range text {
		switch {
		case character == '"' || character == '\\':
			builder.WriteByte('\\')
			builder.WriteRune(character)
		case character < 0x20 || character == 0x7f:
			fmt.Fprintf(&builder, `\u%04X`, character)
		default:
			builder.WriteRune(character)
		}
	}
	builder.WriteByte('"')
	return builder.String()
}
